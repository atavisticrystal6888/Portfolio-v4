#!/usr/bin/env node
/**
 * Route manifest generator (Lane V, 2026-09-30).
 *
 * Sources of truth:
 *   - static routes: src/app/sitemap.ts (the `${SITE_URL}/x` entries + "/")
 *   - case studies: content/case-studies/*.mdx  -> /projects/<slug>
 *   - articles:     content/blog/*.mdx          -> /blog/<slug>
 *   - one path that must render the 404 page
 *
 * Writes tests/e2e/route-manifest.ts and docs/audits/2026-09-30-route-manifest.md.
 * Fails (exit 1, one "FAIL: ..." line per problem, nothing written) if the
 * allowlist is malformed, a case-study .mdx is not in
 * content/approved-case-studies.json, an approved slug has no .mdx, or a
 * withdrawn route is approved, present, or would reappear in the manifest:
 * regenerating the manifest must never bless an accidental publication. The
 * rules and WITHDRAWN_ROUTES live in scripts/lib/case-study-allowlist.mjs.
 */
import fs from "node:fs";
import path from "node:path";
import {
  WITHDRAWN_ROUTES,
  caseStudyPublicationFailures,
  listCaseStudyMdxSlugs,
  readApprovedCaseStudies,
} from "./lib/case-study-allowlist.mjs";

const ROOT = process.cwd();
const NOT_FOUND_PATH = "/this-route-does-not-exist";
const UTILITY = new Set(["/now", "/uses", "/bookshelf", "/changelog"]);

function mdxSlugs(dir) {
  const abs = path.join(ROOT, "content", dir);
  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith(".mdx"))
    .map((f) => f.replace(/\.mdx$/, ""))
    .sort();
}

function staticRoutes() {
  const src = fs.readFileSync(path.join(ROOT, "src/app/sitemap.ts"), "utf8");
  const block = src.split("caseStudyRoutes")[0];
  const found = ["/"];
  for (const m of block.matchAll(/\$\{SITE_URL\}(\/[a-z0-9-]+)`/gi)) found.push(m[1]);
  return [...new Set(found)];
}

function titleOf(dir, slug) {
  const raw = fs.readFileSync(path.join(ROOT, "content", dir, `${slug}.mdx`), "utf8");
  const m = raw.match(/^title:\s*["']?(.+?)["']?\s*$/m);
  return m ? m[1] : slug;
}

function failAndExit(messages) {
  for (const m of messages) console.error(`FAIL: ${m}`);
  console.error("Manifest not written.");
  process.exit(1);
}

// The publication guard runs first, on the one case-study list used below.
const caseStudySlugs = listCaseStudyMdxSlugs(ROOT);
let approved;
try {
  approved = readApprovedCaseStudies(ROOT);
} catch (err) {
  failAndExit([err instanceof Error ? err.message : String(err)]);
}
const guardFailures = caseStudyPublicationFailures({
  approved,
  mdxSlugs: caseStudySlugs,
  withdrawnRoutes: WITHDRAWN_ROUTES,
});
if (guardFailures.length) failAndExit(guardFailures);

const routes = [];
for (const p of staticRoutes()) {
  routes.push({ path: p, kind: UTILITY.has(p) ? "utility" : "index", expectStatus: 200, source: "src/app/sitemap.ts" });
}
for (const s of caseStudySlugs) {
  routes.push({ path: `/projects/${s}`, kind: "case-study", expectStatus: 200, source: `content/case-studies/${s}.mdx`, title: titleOf("case-studies", s) });
}
for (const s of mdxSlugs("blog")) {
  routes.push({ path: `/blog/${s}`, kind: "article", expectStatus: 200, source: `content/blog/${s}.mdx`, title: titleOf("blog", s) });
}
routes.push({ path: NOT_FOUND_PATH, kind: "not-found", expectStatus: 404, source: "src/app/not-found.tsx" });

const leaked = routes.filter((r) => WITHDRAWN_ROUTES.includes(r.path));
if (leaked.length) failAndExit(leaked.map((r) => `withdrawn route ${r.path} is present in the manifest`));

const ts = `// GENERATED by scripts/route-manifest.mjs (npm run routes:manifest). Do not edit by hand.
export type RouteKind = "index" | "utility" | "case-study" | "article" | "not-found";
export interface RouteEntry {
  path: string;
  kind: RouteKind;
  expectStatus: number;
}

export const ROUTES: RouteEntry[] = ${JSON.stringify(
  routes.map(({ path: p, kind, expectStatus }) => ({ path: p, kind, expectStatus })),
  null,
  2
)};

/** Routes that were withdrawn and must 404 and appear nowhere. */
export const WITHDRAWN_ROUTES: string[] = ${JSON.stringify(WITHDRAWN_ROUTES)};

export const NOT_FOUND_PATH = ${JSON.stringify(NOT_FOUND_PATH)};

export const routesOfKind = (kind: RouteKind): RouteEntry[] => ROUTES.filter((r) => r.kind === kind);

/** File-name slug used by screenshots and reports: "/" -> "home", "/a/b" -> "a_b". */
export const routeSlug = (p: string): string => (p === "/" ? "home" : p.slice(1).split("/").join("_"));
`;
fs.writeFileSync(path.join(ROOT, "tests/e2e/route-manifest.ts"), ts);

const counts = routes.reduce((a, r) => ((a[r.kind] = (a[r.kind] || 0) + 1), a), {});
const md = [
  "# Route manifest (2026-09-30)",
  "",
  "Generated by `npm run routes:manifest` (scripts/route-manifest.mjs). Sources: `src/app/sitemap.ts`, `content/case-studies/*.mdx`, `content/blog/*.mdx`, plus one path that must render the 404 page.",
  "",
  `Total: **${routes.length}** routes (${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(", ")}).`,
  "",
  `Withdrawn (must 404 and be absent from sitemap.xml, rss.xml and rendered HTML): ${WITHDRAWN_ROUTES.map((w) => "`" + w + "`").join(", ")}. Enforced by tests/e2e/routes/withdrawn.spec.ts.`,
  "",
  "| # | Path | Kind | Expected status | Source |",
  "|---|------|------|-----------------|--------|",
  ...routes.map((r, i) => `| ${i + 1} | \`${r.path}\` | ${r.kind} | ${r.expectStatus} | ${r.source}${r.title ? ` (${r.title.replace(/\|/g, "\|")})` : ""} |`),
  "",
].join("\n");
fs.mkdirSync(path.join(ROOT, "docs/audits"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "docs/audits/2026-09-30-route-manifest.md"), md);
console.log(`route manifest: ${routes.length} routes`, counts);
